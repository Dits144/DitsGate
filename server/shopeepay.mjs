import { createHmac, randomUUID, timingSafeEqual } from 'node:crypto';

const HOSTS = Object.freeze({
  uat: 'https://api.uat.wallet.airpay.co.id',
  production: 'https://api.wallet.airpay.co.id',
});
const ENDPOINTS = Object.freeze(Object.fromEntries(Object.entries(HOSTS).map(([environment, host]) => [environment, `${host}/v3/merchant-host/transaction/check`])));
const QR_ENDPOINTS = Object.freeze(Object.fromEntries(Object.entries(HOSTS).map(([environment, host]) => [environment, `${host}/v3/merchant-host/qr/create`]))); 
// The public docs require a signed response but do not specify the header name.
// Never supply global fetch here: callers must inject a controlled test transport until
// the exact onboarding contract is confirmed and the response parser is live-tested.
const sign = (raw, secret) => createHmac('sha256', secret).update(raw).digest();
const validId = value => typeof value === 'string' && value.length > 0 && value.length <= 128 && /^[A-Za-z0-9][A-Za-z0-9._:-]*$/.test(value);
export function shopeepayConfig(env) {
  const environment = Object.hasOwn(ENDPOINTS, env.SHOPEEPAY_ENV) ? env.SHOPEEPAY_ENV : null;
  return {
    configured: !!(environment && validId(env.SHOPEEPAY_CLIENT_ID) && typeof env.SHOPEEPAY_SECRET === 'string' && env.SHOPEEPAY_SECRET.length > 0 && validId(env.SHOPEEPAY_MERCHANT_EXT_ID) && validId(env.SHOPEEPAY_STORE_EXT_ID)),
    environment, status: 'not_verified', checkAvailable: false,
  };
}

// Test-only transport injection. The public documentation describes response signing but
// does not name its header. A real transport must remain disabled until confirmed by ShopeePay.
// A signed fixture proves response parsing, not a live provider order. This function
// deliberately cannot be reached from HTTP routes and never writes to the ledger.
export async function createShopeePayQrFixture({ paymentReferenceId, amount, env, fetchImpl }) {
  if (!shopeepayConfig(env).configured || typeof fetchImpl !== 'function') throw new Error('probe_unavailable');
  // MPM's IDR amount uses hundredths; references are generated by the merchant.
  if (!validId(paymentReferenceId) || paymentReferenceId.length > 64 || !Number.isSafeInteger(amount) || amount < 1 || amount > 999_999_999 || !Number.isSafeInteger(amount * 100)) throw new Error('invalid_input');
  const request_id = randomUUID();
  const raw = JSON.stringify({ request_id, amount: amount * 100, currency: 'IDR', merchant_ext_id: env.SHOPEEPAY_MERCHANT_EXT_ID, store_ext_id: env.SHOPEEPAY_STORE_EXT_ID, payment_reference_id: paymentReferenceId });
  try {
    const response = await fetchImpl(QR_ENDPOINTS[env.SHOPEEPAY_ENV], {
      method: 'POST', redirect: 'error', signal: AbortSignal.timeout(8000),
      headers: { 'content-type': 'application/json', 'X-Airpay-ClientId': env.SHOPEEPAY_CLIENT_ID, 'X-Airpay-Req-H': sign(raw, env.SHOPEEPAY_SECRET).toString('base64') }, body: raw,
    });
    if (!response.ok) throw new Error('probe_failed');
    const signature = response.headers.get('X-Airpay-Resp-H');
    if (typeof signature !== 'string' || !/^[A-Za-z0-9+/]{43}=$/.test(signature)) throw new Error('probe_failed');
    const rawResponse = await response.text();
    const actual = Buffer.from(signature, 'base64');
    if (Buffer.byteLength(rawResponse) > 32768 || actual.length !== 32 || !timingSafeEqual(sign(rawResponse, env.SHOPEEPAY_SECRET), actual)) throw new Error('probe_failed');
    const data = JSON.parse(rawResponse);
    if (data?.request_id !== request_id || data?.errcode !== 0 || typeof data.qr_content !== 'string' || !data.qr_content.startsWith('000201') || data.qr_content.length > 4096 || (data.qr_url != null && (typeof data.qr_url !== 'string' || !data.qr_url.startsWith(`${HOSTS[env.SHOPEEPAY_ENV]}/v3/merchant-host/qr/download?`)))) throw new Error('probe_failed');
    return { paymentReferenceId, amount, qrContent: data.qr_content, verification: 'signed_fixture_only', paymentVerified: false };
  } catch { throw new Error('probe_failed'); }
}

export async function checkShopeePay({ referenceId, amount, env, fetchImpl }) {
  if (!shopeepayConfig(env).configured || typeof fetchImpl !== 'function') throw new Error('probe_unavailable');
  if (!validId(referenceId) || !Number.isSafeInteger(amount) || amount < 1 || amount > 999_999_999 || !Number.isSafeInteger(amount * 100)) throw new Error('invalid_input');
  const request_id = randomUUID();
  const raw = JSON.stringify({ request_id, reference_id: referenceId, transaction_type: 13, merchant_ext_id: env.SHOPEEPAY_MERCHANT_EXT_ID, store_ext_id: env.SHOPEEPAY_STORE_EXT_ID, amount: amount * 100 });
  let response;
  try {
    response = await fetchImpl(ENDPOINTS[env.SHOPEEPAY_ENV], {
      method: 'POST', redirect: 'error', signal: AbortSignal.timeout(8000),
      headers: { 'content-type': 'application/json', 'X-Airpay-ClientId': env.SHOPEEPAY_CLIENT_ID, 'X-Airpay-Req-H': sign(raw, env.SHOPEEPAY_SECRET).toString('base64') },
      body: raw,
    });
    if (!response.ok) throw new Error('probe_failed');
    // Header name is provisional, sourced from older third-party-hosted integration material.
    // Even a valid fixture is NOT a payment verification without a provider-created order.
    const signature = response.headers.get('X-Airpay-Resp-H');
    if (typeof signature !== 'string' || !/^[A-Za-z0-9+/]{43}=$/.test(signature)) throw new Error('probe_failed');
    const expected = Buffer.from(signature, 'base64');
    const rawResponse = await response.text();
    if (Buffer.byteLength(rawResponse) > 32768 || expected.length !== 32 || !timingSafeEqual(sign(rawResponse, env.SHOPEEPAY_SECRET), expected)) throw new Error('probe_failed');
    const data = JSON.parse(rawResponse);
    const tx = data?.transaction;
    if (data?.request_id !== request_id || data?.errcode !== 0 || !tx || Array.isArray(tx) || tx.reference_id !== referenceId || tx.merchant_ext_id !== env.SHOPEEPAY_MERCHANT_EXT_ID || tx.store_ext_id !== env.SHOPEEPAY_STORE_EXT_ID || tx.amount !== amount * 100 || tx.transaction_type !== 13 || ![1,2,3,4,6,7].includes(tx.status)) throw new Error('probe_failed');
    return { verification: 'signed_response_received', paymentVerified: false, providerStatus: tx.status };
  } catch { throw new Error('probe_failed'); }
}
